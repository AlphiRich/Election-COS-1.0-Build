/**
 * Election Campaign OS — Campaign Director: the deterministic ECOS tools.
 *
 * The tool LOGIC, as plain tested functions. `mcpServer.ts` and
 * `ecosLangchainTools.ts` register these for a model to call; keeping the logic
 * here means the honesty rules are proven without a transport or a model.
 *
 * Seat figures come from the REAL, mirrored Schedule 1 engine
 * (`./engine/seatCalculator` — `allocateSeats`, the Item 12 quota) over REAL
 * certified inputs:
 *   - NW405 (JB Marks) 2021, `./engine/nw405Example`;
 *   - the certified LGE 2026 result for all 18 North West local municipalities,
 *     snapshotted into `./engine/nw-seat-inputs-2026.json` from the app's
 *     `lge2026` pipeline (see `src/modules/analytics/agentBaseline2026.ts`).
 * Both are generated by `npm run gen:agent-engine` and guarded against drift by
 * `agentEngineMirror.test.ts`. The statutory formula is never reimplemented; a
 * scenario swing is a transparent, labelled USER ASSUMPTION on top of it.
 *
 * A municipality/year this runtime does not hold FAILS CLOSED rather than
 * returning a figure it cannot stand behind.
 */
import type { HarnessContext } from './state';
import { allocateSeats, type SeatAllocationResult } from './engine/seatCalculator';
import { NW405_2021_EXAMPLE } from './engine/nw405Example';
import nwSeats2026 from './engine/nw-seat-inputs-2026.json';

/** The MCP tool result shape (a subset of CallToolResult; the index signature
 * keeps it assignable to the SDK's CallToolResult without pulling its type in). */
export interface McpToolResult {
  content: { type: 'text'; text: string }[];
  isError?: boolean;
  [x: string]: unknown;
}

function textResult(text: string, isError = false): McpToolResult {
  return { content: [{ type: 'text', text }], isError };
}

type ElectionYear = '2026' | '2021';

interface PartyVotes {
  id: string;
  name: string;
  votes: number;
  wardSeatsWon: number;
}

interface ResolvedBaseline {
  code: string;
  name: string;
  year: ElectionYear;
  source: string;
  delimitationId: string;
  totalSeats: number;
  totalValidVotes: number;
  independentWardSeats: number;
  noPRListWardSeats: number;
  parties: PartyVotes[];
}

interface CertifiedSeatInput2026 {
  code: string;
  name: string;
  delimitationId: string;
  totalSeats: number;
  totalValidVotes: number;
  independentWardSeats: number;
  noPRListWardSeats: number;
  parties: PartyVotes[];
}

const NW_2026 = nwSeats2026 as Record<string, CertifiedSeatInput2026>;

/** Codes/years this runtime holds a certified result for, for a clear refusal. */
const COVERAGE = `NW405 (JB Marks) 2021, or any of the 18 North West local municipalities (${Object.keys(NW_2026)
  .sort()
  .join(', ')}) for 2026`;

/** The certified baseline for a municipality + year, or null when not held here. */
function resolveBaseline(codeRaw: string | undefined, year: ElectionYear): ResolvedBaseline | null {
  const code = codeRaw?.trim().toUpperCase();
  if (!code) return null;

  if (year === '2021') {
    if (code !== 'NW405') return null;
    return {
      code: 'NW405',
      name: 'JB Marks',
      year,
      source: 'IEC Seat Calculation Detail for NW405 (2021 LGE), transcribed — see docs/nw405-seed-data.md',
      delimitationId: NW405_2021_EXAMPLE.delimitationId,
      totalSeats: NW405_2021_EXAMPLE.totalSeats,
      totalValidVotes: NW405_2021_EXAMPLE.totalValidVotes,
      independentWardSeats: NW405_2021_EXAMPLE.independentWardSeats,
      noPRListWardSeats: NW405_2021_EXAMPLE.noPRListWardSeats,
      parties: NW405_2021_EXAMPLE.parties.map((p) => ({ id: p.id, name: p.name, votes: p.votes, wardSeatsWon: p.wardSeatsWon })),
    };
  }

  const entry = NW_2026[code];
  if (!entry) return null;
  return {
    code: entry.code,
    name: entry.name,
    year: '2026',
    source: `Certified LGE 2026 result for ${entry.name} (${entry.code}) — IEC, via modules/lge2026`,
    delimitationId: entry.delimitationId,
    totalSeats: entry.totalSeats,
    totalValidVotes: entry.totalValidVotes,
    independentWardSeats: entry.independentWardSeats,
    noPRListWardSeats: entry.noPRListWardSeats,
    parties: entry.parties.map((p) => ({ id: p.id, name: p.name, votes: p.votes, wardSeatsWon: p.wardSeatsWon })),
  };
}

function allocate(b: ResolvedBaseline, parties: PartyVotes[], totalValidVotes: number): SeatAllocationResult {
  return allocateSeats({
    totalValidVotes,
    totalSeats: b.totalSeats,
    independentWardSeats: b.independentWardSeats,
    noPRListWardSeats: b.noPRListWardSeats,
    delimitationId: b.delimitationId,
    parties,
  });
}

function seatSummary(res: SeatAllocationResult) {
  return {
    quota: res.quota,
    newQuota: res.newQuota,
    councilSizeFinal: res.councilSizeFinal,
    totalSeatsAllocated: res.totalSeatsAllocated,
    pendingSeats: res.pendingSeats,
    excessiveParties: res.excessiveParties,
    notes: res.notes,
    delimitationId: res.delimitationId,
    parties: res.parties.map((p) => ({
      id: p.id,
      name: p.name,
      votes: p.votes,
      wardSeats: p.wardSeatsWon,
      prSeats: p.prSeats,
      totalSeats: p.totalSeats,
    })),
  };
}

// ---- Reader: war-room counters -------------------------------------------

/**
 * Reads tenant-scoped war-room counters. Injected so the tool is tested without
 * Firestore and can never read outside its tenant (the reader is handed only
 * `ctx.tenantId`).
 */
export type CounterReader = (tenantId: string, wardIds: string[]) => Promise<Record<string, number>>;

export async function getWarRoomCountersTool(
  ctx: HarnessContext,
  reader: CounterReader,
  wardIds: string[] = [],
): Promise<McpToolResult> {
  const counters = await reader(ctx.tenantId, wardIds);
  // Honest empty state: an empty object is reported as-is, never interpolated.
  // The counters are TENANT-WIDE (ward-level counters are not held), so the
  // result says so, and never echoes requested wards as if it were scoped to them.
  return textResult(
    JSON.stringify({
      tenantId: ctx.tenantId,
      scope: 'tenant',
      counters,
      ...(wardIds.length > 0
        ? { note: `Ward-level counters are not held; these are tenant-wide totals, not figures for ${wardIds.join(', ')}.` }
        : {}),
    }),
  );
}

// ---- Certified baseline ---------------------------------------------------

export interface CertifiedBaselineInput {
  municipality_code: string;
  election_year?: ElectionYear;
}

/**
 * The certified result for a municipality, run through the real Schedule 1
 * engine. Serves NW405 2021 and the 18 NW locals' 2026 results; anything else
 * fails closed rather than inventing a figure.
 */
export function getCertifiedBaselineTool(input: CertifiedBaselineInput): McpToolResult {
  const year: ElectionYear = input.election_year ?? '2026';
  const b = resolveBaseline(input.municipality_code, year);
  if (!b) {
    return textResult(
      `No certified baseline is held in this runtime for ${input.municipality_code ?? '(none)'} ${year}. ` +
        `This runtime holds ${COVERAGE}. It refuses rather than returning an unverified figure.`,
      true,
    );
  }
  const res = allocate(b, b.parties, b.totalValidVotes);
  return textResult(
    JSON.stringify({
      municipality_code: b.code,
      name: b.name,
      election_year: b.year,
      source: b.source,
      totalValidVotes: b.totalValidVotes,
      totalSeats: b.totalSeats,
      ...seatSummary(res),
    }),
  );
}

// ---- Schedule 1 scenario --------------------------------------------------

export interface Schedule1ScenarioInput {
  municipality_code: string;
  election_year?: ElectionYear;
  seed?: number;
  turnout_delta_pct?: number;
  party_swings_pct?: Record<string, number>;
  assumption_acknowledged_by_user?: boolean;
}

/**
 * Propagate user-stated swings and a turnout delta through the authoritative
 * Schedule 1 quota. A simple proportional swing on the baseline's PR votes — a
 * USER ASSUMPTION, never presented as sourced — with ward seats held at their
 * certified values. It is a PR-seat scenario, not a ward-by-ward flip simulation
 * (that richer model stays in the app). Defaults to the 2026 baseline.
 */
export function runSchedule1ScenarioTool(input: Schedule1ScenarioInput): McpToolResult {
  const year: ElectionYear = input.election_year ?? '2026';
  const b = resolveBaseline(input.municipality_code, year);
  if (!b) {
    return textResult(
      `Scenario has no certified baseline for ${input.municipality_code ?? '(none)'} ${year} in this runtime. ` +
        `This runtime holds ${COVERAGE}.`,
      true,
    );
  }
  if (input.assumption_acknowledged_by_user !== true) {
    return textResult(
      'Scenario requires assumption_acknowledged_by_user: true — a swing and turnout delta are your ' +
        'assumptions, not sourced figures, and the run will not proceed without that acknowledgement.',
      true,
    );
  }

  const swings = input.party_swings_pct ?? {};
  const turnoutFactor = 1 + (input.turnout_delta_pct ?? 0) / 100;
  const parties = b.parties.map((p) => {
    const swingPct = swings[p.id] ?? 0;
    const votes = Math.max(0, Math.round(p.votes * (1 + swingPct / 100) * turnoutFactor));
    return { id: p.id, name: p.name, votes, wardSeatsWon: p.wardSeatsWon };
  });
  const totalValidVotes = parties.reduce((s, p) => s + p.votes, 0);
  const res = allocate(b, parties, totalValidVotes);

  return textResult(
    JSON.stringify({
      municipality_code: b.code,
      name: b.name,
      election_year: b.year,
      seed: input.seed ?? null,
      provenance: 'user_assumption_propagated_via_schedule1',
      model_note:
        `Simple proportional swing applied to the ${b.year} PR votes (a user assumption), then the real ` +
        'Schedule 1 Item 12 quota. Ward seats held at their certified values; this is a PR-seat scenario, not a ' +
        'ward-by-ward flip simulation. Deterministic — the seed does not affect the result.',
      turnout_delta_pct: input.turnout_delta_pct ?? 0,
      party_swings_pct: swings,
      totalValidVotes,
      ...seatSummary(res),
    }),
  );
}
